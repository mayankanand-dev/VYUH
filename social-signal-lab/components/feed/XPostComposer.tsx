'use client';

import React, { useState } from 'react';
import {
  Image as ImageIcon,
  Smile,
  Calendar,
  MapPin,
  ListOrdered,
  Globe,
  Sparkles,
  AlertCircle
} from 'lucide-react';
import { Post } from '@/types/feed';
import { useAnalysisMode } from '@/context/AnalysisModeContext';

interface XPostComposerProps {
  onAddPost: (newPost: Omit<Post, 'id' | 'timestamp' | 'metrics' | 'userInteractions' | 'repliesList'>) => void;
}

export default function XPostComposer({ onAddPost }: XPostComposerProps) {
  const { isAnalysisMode } = useAnalysisMode();
  const [content, setContent] = useState('');
  const [isFocused, setIsFocused] = useState(false);
  const [flagAsAnomaly, setFlagAsAnomaly] = useState(false);

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (!content.trim()) return;

    const hashtags = content.match(/#[a-zA-Z0-9_]+/g) || [];

    onAddPost({
      authorName: 'Lead Evaluator',
      authorHandle: '@lab_analyst_01',
      authorInitials: 'LA',
      authorAvatarBg: 'bg-slate-900',
      isVerified: true,
      isFollowingAuthor: true,
      content: content.trim(),
      hashtags,
      detectionFinding: flagAsAnomaly
        ? {
            badgeLabel: 'Simulated finding',
            severity: 'medium',
            ruleTriggered: 'User-Injected Synthetic Anomaly (Mock Rule SIM-001)',
            confidenceScore: 0.86,
            reason: 'Manually synthesized event injected during active evaluator session with the simulated detection flag enabled.',
            detectedSignals: [
              'Manual injection flag active',
              'Evaluator session provenance: Authenticated benchmark harness',
              'Heuristic anomaly marker flagged by operator'
            ],
            disclaimer: 'DEMO FINDING: Statically evaluated for testbed evaluation. Not generated by a live production AI model.'
          }
        : undefined,
    });

    setContent('');
    setFlagAsAnomaly(false);
    setIsFocused(false);
  };

  const loadPreset = (text: string, flag: boolean) => {
    setContent(text);
    setFlagAsAnomaly(flag);
    setIsFocused(true);
  };

  return (
    <div className="border-b border-[#2f3336] px-4 pt-3 pb-2 bg-black select-none">
      <div className="flex gap-3">
        {/* User avatar */}
        <div className="shrink-0 pt-1">
          <div className="w-10 h-10 rounded-full bg-[#16181c] border border-[#2f3336] text-white flex items-center justify-center font-bold text-sm">
            LA
          </div>
        </div>

        {/* Composer Form */}
        <form onSubmit={handleSubmit} className="flex-1 min-w-0">
          {/* Who can reply indicator */}
          {isFocused && (
            <button
              type="button"
              className="flex items-center gap-1.5 text-xs font-bold text-[#1d9bf0] hover:bg-[#1d9bf0]/10 px-3 py-1 rounded-full mb-1 transition-colors w-fit cursor-pointer"
            >
              <Globe className="w-3.5 h-3.5" />
              <span>Everyone can reply</span>
            </button>
          )}

          <textarea
            value={content}
            onChange={(e) => setContent(e.target.value)}
            onFocus={() => setIsFocused(true)}
            placeholder="What is happening?!"
            rows={isFocused || content.length > 0 ? 3 : 2}
            className="w-full text-[#e7e9ea] placeholder-[#71767b] text-[19px] leading-6 border-0 focus:outline-hidden focus:ring-0 p-0 resize-none bg-transparent"
          />

          {/* Quick preset scenario helper visible if in Analysis Mode */}
          {isAnalysisMode && (
            <div className="flex items-center gap-2 flex-wrap py-2 border-t border-[#2f3336]/60">
              <span className="text-[11px] text-[#71767b] font-medium flex items-center gap-1">
                <Sparkles className="w-3 h-3 text-amber-400" /> Test Presets:
              </span>
              <button
                type="button"
                onClick={() =>
                  loadPreset(
                    'URGENT: Municipal water plant intake sensors triggered remote emergency shutdown. Contaminants suspected! #WaterPanic',
                    true
                  )
                }
                className="text-[11px] px-2 py-0.5 rounded-full bg-[#16181c] hover:bg-[#202327] text-[#e7e9ea] border border-[#2f3336] transition-colors cursor-pointer"
              >
                Water Panic
              </button>
              <button
                type="button"
                onClick={() =>
                  loadPreset(
                    'Our latest multi-agent consensus graph benchmark code is open-sourced today. Reproducibility guide in repo! #GraphAI #OpenScience',
                    false
                  )
                }
                className="text-[11px] px-2 py-0.5 rounded-full bg-[#16181c] hover:bg-[#202327] text-[#e7e9ea] border border-[#2f3336] transition-colors cursor-pointer"
              >
                Control Paper
              </button>

              <label className="flex items-center gap-1.5 text-[11px] text-[#71767b] ml-auto cursor-pointer">
                <input
                  type="checkbox"
                  checked={flagAsAnomaly}
                  onChange={(e) => setFlagAsAnomaly(e.target.checked)}
                  className="rounded bg-[#202327] border-[#2f3336] text-[#1d9bf0] focus:ring-[#1d9bf0]"
                />
                <span className="flex items-center gap-1 text-[#e7e9ea]">
                  <AlertCircle className="w-3 h-3 text-amber-400" />
                  Simulate Anomaly
                </span>
              </label>
            </div>
          )}

          {/* Bottom Bar: Action icons & Post button */}
          <div className="flex items-center justify-between pt-2 border-t border-[#2f3336]">
            {/* Toolbar icons */}
            <div className="flex items-center gap-0.5 text-[#1d9bf0]">
              <button
                type="button"
                title="Media"
                className="p-2 rounded-full hover:bg-[#1d9bf0]/10 transition-colors cursor-pointer"
              >
                <ImageIcon className="w-5 h-5" />
              </button>
              <button
                type="button"
                title="Poll"
                className="p-2 rounded-full hover:bg-[#1d9bf0]/10 transition-colors cursor-pointer"
              >
                <ListOrdered className="w-5 h-5" />
              </button>
              <button
                type="button"
                title="Emoji"
                className="p-2 rounded-full hover:bg-[#1d9bf0]/10 transition-colors cursor-pointer"
              >
                <Smile className="w-5 h-5" />
              </button>
              <button
                type="button"
                title="Schedule"
                className="p-2 rounded-full hover:bg-[#1d9bf0]/10 transition-colors cursor-pointer"
              >
                <Calendar className="w-5 h-5" />
              </button>
              <button
                type="button"
                title="Location"
                className="p-2 rounded-full hover:bg-[#1d9bf0]/10 transition-colors cursor-pointer opacity-50"
              >
                <MapPin className="w-5 h-5" />
              </button>
            </div>

            {/* Post button & character count */}
            <div className="flex items-center gap-3">
              {content.length > 0 && (
                <span
                  className={`text-xs ${
                    content.length > 250 ? 'text-rose-400 font-bold' : 'text-[#71767b]'
                  }`}
                >
                  {280 - content.length}
                </span>
              )}
              <button
                type="submit"
                disabled={!content.trim()}
                className="bg-[#1d9bf0] hover:bg-[#1a8cd8] active:bg-[#177cc0] disabled:opacity-50 text-white font-bold text-[15px] px-4 py-1.5 rounded-full transition-all cursor-pointer"
              >
                Post
              </button>
            </div>
          </div>
        </form>
      </div>
    </div>
  );
}
