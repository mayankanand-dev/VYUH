'use client';

import React, { useState } from 'react';
import { Send, Sparkles, Tag, AlertCircle } from 'lucide-react';
import { Post } from '@/types/feed';

interface PostComposerProps {
  onAddPost: (newPost: Omit<Post, 'id' | 'timestamp' | 'metrics' | 'userInteractions' | 'repliesList'>) => void;
}

export default function PostComposer({ onAddPost }: PostComposerProps) {
  const [content, setContent] = useState('');
  const [selectedTag, setSelectedTag] = useState<string>('');
  const [simulateDetection, setSimulateDetection] = useState<boolean>(false);
  const [isFocused, setIsFocused] = useState(false);

  const sampleTags = ['#SimulationSignal', '#DisinfoTest', '#GridRumor', '#HealthClaim', '#OpenResearch'];

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (!content.trim()) return;

    let finalContent = content.trim();
    if (selectedTag && !finalContent.includes(selectedTag)) {
      finalContent = `${finalContent} ${selectedTag}`;
    }

    const hashtags = finalContent.match(/#[a-zA-Z0-9_]+/g) || (selectedTag ? [selectedTag] : []);

    onAddPost({
      authorName: 'Lead Evaluator',
      authorHandle: '@lab_analyst_01',
      authorInitials: 'LA',
      authorAvatarBg: 'bg-slate-900',
      isVerified: true,
      content: finalContent,
      hashtags,
      detectionFinding: simulateDetection
        ? {
            badgeLabel: 'Simulated finding',
            severity: 'medium',
            ruleTriggered: 'User-Injected Synthetic Anomaly (Mock Rule SIM-001)',
            confidenceScore: 0.81,
            reason: 'This signal was injected manually during active evaluator session with the simulated detection flag enabled.',
            detectedSignals: [
              'Manual injection tag active',
              'Evaluator session provenance: Authenticated benchmark harness',
              'Heuristic anomaly marker flagged by operator'
            ],
            disclaimer: 'DEMO FINDING: Statically evaluated for testbed evaluation. Not generated by a live production AI model.'
          }
        : undefined,
    });

    setContent('');
    setSelectedTag('');
    setSimulateDetection(false);
    setIsFocused(false);
  };

  const loadPreset = (presetText: string, tag: string, flagDetection: boolean) => {
    setContent(presetText);
    setSelectedTag(tag);
    setSimulateDetection(flagDetection);
  };

  return (
    <div className="border-b border-slate-200/80 bg-white p-4 transition-all">
      <div className="flex gap-3">
        {/* User avatar */}
        <div className="w-10 h-10 rounded-full bg-slate-900 text-white flex items-center justify-center font-bold text-xs shrink-0 shadow-2xs">
          LA
        </div>

        {/* Composer body */}
        <form onSubmit={handleSubmit} className="flex-1 space-y-3">
          <textarea
            value={content}
            onChange={(e) => setContent(e.target.value)}
            onFocus={() => setIsFocused(true)}
            placeholder="Compose a synthetic social signal or inject a scenario event..."
            rows={isFocused || content.length > 0 ? 3 : 2}
            className="w-full text-slate-800 placeholder-slate-400 text-sm sm:text-base resize-none border-0 focus:outline-hidden focus:ring-0 p-1 bg-transparent"
          />

          {/* Quick preset scenarios dropdown/buttons to make testing rapid */}
          <div className="flex items-center gap-1.5 flex-wrap pt-1">
            <span className="text-[11px] text-slate-400 font-medium flex items-center gap-1">
              <Sparkles className="w-3 h-3 text-amber-500" /> Presets:
            </span>
            <button
              type="button"
              onClick={() =>
                loadPreset(
                  'BREAKING: Multiple automated telemetry sensors report anomalous fluctuation at the central water reclamation plant. Testing protocol verification requested. #WaterSafety',
                  '#WaterSafety',
                  true
                )
              }
              className="text-[11px] px-2 py-0.5 rounded-full bg-slate-100 text-slate-600 hover:bg-slate-200 transition-colors"
            >
              Water Rumor
            </button>
            <button
              type="button"
              onClick={() =>
                loadPreset(
                  'Published initial benchmark metrics for synthetic graph embedding latency across 50,000 node clusters. Reproducibility code pushed to lab repo. #GraphAI',
                  '#GraphAI',
                  false
                )
              }
              className="text-[11px] px-2 py-0.5 rounded-full bg-slate-100 text-slate-600 hover:bg-slate-200 transition-colors"
            >
              Control Post
            </button>
            <button
              type="button"
              onClick={() =>
                loadPreset(
                  'Unverified advisory: Local municipal bus transit schedules suspended due to cyber disruption. Check station boards! #TransitAlert',
                  '#TransitAlert',
                  true
                )
              }
              className="text-[11px] px-2 py-0.5 rounded-full bg-slate-100 text-slate-600 hover:bg-slate-200 transition-colors"
            >
              Transit Alert
            </button>
          </div>

          {/* Controls Bar */}
          <div className="flex items-center justify-between pt-2 border-t border-slate-100">
            {/* Tag and Detection Simulation toggle */}
            <div className="flex items-center gap-2 flex-wrap">
              <div className="flex items-center gap-1">
                <Tag className="w-3.5 h-3.5 text-slate-400" />
                <select
                  value={selectedTag}
                  onChange={(e) => setSelectedTag(e.target.value)}
                  className="text-xs bg-slate-50 border border-slate-200 text-slate-700 rounded-md px-1.5 py-1 focus:outline-hidden focus:ring-1 focus:ring-blue-500 cursor-pointer"
                >
                  <option value="">Attach Tag...</option>
                  {sampleTags.map((t) => (
                    <option key={t} value={t}>
                      {t}
                    </option>
                  ))}
                </select>
              </div>

              {/* Simulation flag checkbox */}
              <label className="flex items-center gap-1.5 cursor-pointer text-xs text-slate-600 bg-slate-50 hover:bg-slate-100 border border-slate-200 px-2 py-1 rounded-md transition-colors">
                <input
                  type="checkbox"
                  checked={simulateDetection}
                  onChange={(e) => setSimulateDetection(e.target.checked)}
                  className="w-3 h-3 text-blue-600 rounded-xs border-slate-300 focus:ring-blue-500"
                />
                <span className="flex items-center gap-1 text-[11px]">
                  <AlertCircle className="w-3 h-3 text-amber-600" />
                  Flag as Simulated Anomaly
                </span>
              </label>
            </div>

            {/* Submit button */}
            <div className="flex items-center gap-3">
              <span className={`text-xs ${content.length > 240 ? 'text-rose-500 font-bold' : 'text-slate-400'}`}>
                {content.length}/280
              </span>
              <button
                type="submit"
                disabled={!content.trim()}
                className="px-4 py-1.5 bg-slate-900 hover:bg-slate-800 disabled:opacity-40 disabled:hover:bg-slate-900 text-white font-semibold text-xs sm:text-sm rounded-full transition-all shadow-xs flex items-center gap-1.5 cursor-pointer"
              >
                <Send className="w-3.5 h-3.5" />
                <span>Post</span>
              </button>
            </div>
          </div>
        </form>
      </div>
    </div>
  );
}
